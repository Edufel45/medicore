@pytest.mark.integration
@pytest.mark.django_db
def test_patient_list_search(client_reception, sample_patient):
    """Search finds a patient by name, SID, NID, phone."""
    for query in [
        sample_patient.full_name,
        sample_patient.sid,
        sample_patient.national_id,
        sample_patient.phone,
    ]:
        response = client_reception.get(f"/patients/?q={query}")
        assert response.status_code == 200
        assert sample_patient.sid in response.content.decode()