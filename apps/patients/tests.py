@pytest.mark.integration
@pytest.mark.django_db
def test_registration_creates_patient_visit_bill(client_reception):
    """POST to /patients/register/ creates Patient + Visit + Bill + Payment."""
    response = client_reception.post("/patients/register/", {
        "full_name": "Test Register",
        "national_id": "55556666",
        "phone": "0712345678",
        "sex": "F",
        "age_years": 28,
        "sha_number": "DEMO-1001",
        "reason_for_visit": "Headache",
        "collect_registration_fee": "on",
    })
    # Redirects to home on success
    assert response.status_code == 302

    p = Patient.objects.get(national_id="55556666")
    assert p.full_name == "Test Register"
    assert p.sha_status == "active"
    assert p.sha_verified_at is not None

    visit = Visit.objects.get(patient=p)
    assert visit.stage == "doctor"
    assert visit.registration_fee_paid is True
    assert visit.queue_number.startswith("A-")

    bill = Bill.objects.get(visit=visit)
    assert float(bill.total_amount) == 200.00
    assert float(bill.paid_amount) == 200.00
    assert bill.status == "settled"

    payment = Payment.objects.get(bill=bill)
    assert payment.method == "mpesa"
    assert payment.status == "success"


@pytest.mark.integration
@pytest.mark.django_db
def test_registration_blocks_duplicate_nid(client_reception):
    """Registering a second active patient with same NID is blocked."""
    client_reception.post("/patients/register/", {
        "full_name": "A", "national_id": "77778888", "phone": "0711000001",
        "sex": "F", "age_years": 25, "sha_number": "DEMO-1001",
        "reason_for_visit": "X", "collect_registration_fee": "on",
    })
    # Second attempt — same NID, different phone
    response = client_reception.post("/patients/register/", {
        "full_name": "B", "national_id": "77778888", "phone": "0711000002",
        "sex": "M", "age_years": 30, "sha_number": "DEMO-1002",
        "reason_for_visit": "Y", "collect_registration_fee": "on",
    })
    # No redirect — form re-renders with error
    assert response.status_code == 200
    assert Patient.objects.filter(national_id="77778888").count() == 1


