@pytest.mark.unit
@pytest.mark.django_db
def test_patient_sid_autogenerated(reception_user):
    """A new patient gets a System ID like MC-YYYY-NNNN."""
    p = Patient.objects.create(
        full_name="John Doe",
        national_id="12345678",
        phone="0712345678",
        sex="M",
        age_years=40,
        created_by=reception_user,
    )
    assert p.sid.startswith("MC-")
    assert len(p.sid) == 12          # e.g. MC-2026-0001
    assert p.sid.split("-")[-1] == "0001"


@pytest.mark.unit
@pytest.mark.django_db
def test_patient_sid_increments(reception_user):
    """Second patient gets MC-YYYY-0002."""
    p1 = Patient.objects.create(
        full_name="A", national_id="11111111", phone="0711000001",
        sex="F", age_years=20, created_by=reception_user,
    )
    p2 = Patient.objects.create(
        full_name="B", national_id="22222222", phone="0711000002",
        sex="M", age_years=22, created_by=reception_user,
    )
    assert p1.sid.endswith("0001")
    assert p2.sid.endswith("0002")


@pytest.mark.unit
@pytest.mark.django_db
def test_patient_age_from_dob(reception_user):
    """If date_of_birth is set, age is computed correctly."""
    from datetime import date
    p = Patient.objects.create(
        full_name="Test", national_id="33333333", phone="0711000003",
        sex="F", date_of_birth=date(1990, 6, 15),
        created_by=reception_user,
    )
    expected = date.today().year - 1990
    if (date.today().month, date.today().day) < (6, 15):
        expected -= 1
    assert p.age == expected


